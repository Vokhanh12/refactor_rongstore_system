CREATE TYPE ROLE_SCOPE_TYPE AS ENUM (
    'GLOBAL',
    'TENANT',
    'UNIT'
);

CREATE TABLE ROLE_ASSIGNMENTS (
    ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    USER_ID UUID NOT NULL,
    ROLE_ID UUID NOT NULL,

    SCOPE_ID UUID,
    SCOPE_TYPE ROLE_SCOPE_TYPE NOT NULL,

    ASSIGNED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ASSIGNED_BY UUID,

    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CREATED_BY UUID,
    UPDATED_BY UUID,

    CONSTRAINT FK_ROLE_ASSIGNMENTS_ROLE
        FOREIGN KEY (ROLE_ID)
        REFERENCES ROLES (ID)
        ON DELETE CASCADE,

    CONSTRAINT CK_ROLE_ASSIGNMENTS_SCOPE
        CHECK (
            (
                SCOPE_TYPE = 'GLOBAL'
                AND SCOPE_ID IS NULL
            )
            OR
            (
                SCOPE_TYPE IN ('TENANT', 'UNIT')
                AND SCOPE_ID IS NOT NULL
            )
        )
);

-- Prevent duplicate role assignment
CREATE UNIQUE INDEX UQ_ROLE_ASSIGNMENTS_SCOPE
    ON ROLE_ASSIGNMENTS (
        USER_ID,
        ROLE_ID,
        SCOPE_TYPE,
        SCOPE_ID
    ) NULLS NOT DISTINCT;

CREATE INDEX IDX_ROLE_ASSIGNMENTS_USER
    ON ROLE_ASSIGNMENTS (USER_ID);

CREATE INDEX IDX_ROLE_ASSIGNMENTS_ROLE
    ON ROLE_ASSIGNMENTS (ROLE_ID);

CREATE INDEX IDX_ROLE_ASSIGNMENTS_SCOPE
    ON ROLE_ASSIGNMENTS (SCOPE_TYPE, SCOPE_ID);

CREATE INDEX IDX_ROLE_ASSIGNMENTS_USER_SCOPE
    ON ROLE_ASSIGNMENTS (
        USER_ID,
        SCOPE_TYPE,
        SCOPE_ID
    );

-- +goose StatementEnd


-- +goose Down

-- +goose StatementBegin

DROP TABLE IF EXISTS ROLE_ASSIGNMENTS;

DROP TYPE IF EXISTS ROLE_SCOPE_TYPE;

-- +goose StatementEnd